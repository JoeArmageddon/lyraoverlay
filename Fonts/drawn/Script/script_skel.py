def ent(x1, y1):
    return spline([(0, J), (x1 * 0.5, J + (y1 - J) * 0.45), (x1, y1)], t0=(1, 1.5))

def ext(x0, y0, adv):
    return spline([(x0, y0), (x0 + (adv - x0) * 0.55, y0 + 5), (adv, J)], t0=(1, 0), t1=(1, 1.1))

def stem_exit(x, ytop, adv, ymid=None):
    return spline([(x, ytop), (x, 250), (x, 95), (x + 22, 26), (x + (adv - x) * 0.55, 8), (adv, J)], t0=(0, -1), t1=(1, 1.1))

