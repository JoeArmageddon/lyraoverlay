def asc_loop(upto=None):
    pts = LOOP if upto is None else LOOP[:upto]
    return spline(pts, t0=(1, 1.6), t1=(0, -1))

def bowl(cx, cy, rx, ry, a0=90, a1=450):
    return arc(cx, cy, rx, ry, a0, a1, step=5)

