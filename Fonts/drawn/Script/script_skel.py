"""Lyra Script skeletons: upright connected-script centre-lines.
Every lowercase glyph starts at (0, J) and ends at (adv, J) with the same rising tangent,
so any two letters join with a continuous hairline.  Strokes are separate pen strokes
(no pen continuity needed), pressure comes from stroke direction in the pen model."""
