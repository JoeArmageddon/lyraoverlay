#!/usr/bin/env python3
"""Lyra Blade Drawn - razor-sharp italic.  Run: /tmp/fontvenv/bin/python build_blade.py"""
import os, sys, copy, math
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(1, os.path.dirname(HERE))
import lyrakit as K
import lyrabuild as B
import lyraskel as SK
from lyrakit import Pen


class Cfg: pass


cfg = Cfg()
cfg.name_info = dict(
    family="Lyra Blade Drawn", ps="LyraBladeDrawn-Regular",
    copyright="Copyright (c) 2026 Lyra. Generated by build_blade.py. Licensed under the SIL Open Font License 1.1.",
    description="Razor sharp italic display face: tapered knife-edge strokes, 16 degree slant.",
    license="This Font Software is licensed under the SIL Open Font License, Version 1.1. https://openfontlicense.org")
cfg.corner = "round"
cfg.H, cfg.hsc, cfg.xheight = 700, 500, 500
cfg.W = 440
cfg.sc_w = 0.9
cfg.slant = 16
cfg.italic_angle = -16
cfg.weight_class = 400
cfg.inx, cfg.iny = 38, 7
cfg.step = 6
cfg.join_tol = 30
cfg.dot_r = 36
cfg.pen = Pen(tmin=11, tmax=84, nib=14, exp=1.35, taper=190, taper_pow=0.85, tip=2.2, miter=3.6)
cfg.mark_pen = Pen(tmin=8, tmax=40, nib=14, exp=1.3, taper=45, taper_pow=0.9, tip=1.8, miter=3)
cfg.clip_lo, cfg.clip_hi = -8, 10
cfg.cut = lambda k, lp, ln: 0.5 * k * min(lp, ln)
cfg.cuts = {}
cfg.gap, cfg.cut_len = 0, 0
cfg.dot = lambda cx, cy: [[(cx, cy + 50), (cx + 34, cy), (cx, cy - 50), (cx - 34, cy)]]
cfg.wf = dict(A=1.12, B=.93, C=1.0, D=1.0, E=.84, F=.8, G=1.03, H=1.0, J=.82, K=.98, L=.8, M=1.3, N=1.0,
              O=1.06, P=.93, Q=1.06, R=.96, S=.94, T=.96, U=1.0, V=1.08, W=1.62, X=1.02, Y=1.02, Z=.96,
              AE=1.62, sz=.95)
cfg.wabs = dict(I=2 * cfg.inx + 2, l_lc=170, i_lc=2 * cfg.inx + 2, j_lc=250)
cfg.wf.update({"0": .86, "1": .62, "2": .88, "3": .88, "4": .94, "5": .88, "6": .9, "7": .86, "8": .9, "9": .9})
cfg.pwf = {".": .2, ",": .26, "!": .24, "?": .74, "'": .2, "\"": .46, "‘": .3, "’": .3, "“": .5,
           "”": .5, "-": .56, "–": .8, "—": 1.35, ":": .2, ";": .26, "&": 1.1, "(": .46, ")": .46,
           "/": .62, "\\": .62, "#": .96, "@": 1.5, "%": 1.3, "+": .8, "=": .8, "$": .84, "*": .6,
           "…": 1.2, "_": .9, "~": .8, "^": .7, "<": .7, ">": .7, "[": .42, "]": .42, "{": .5, "}": .5,
           "|": .2, "`": .3, "¡": .24, "¿": .74}
cfg.pwabs = {}
cfg.skel = SK.classic()
cfg.skel["Q"] = [["C", (0, 0, 1), (1, 0, 1), (1, 1, 1), (0, 1, 1)], [(.55, .26), (1.08, -.1)]]
cfg.oslash = lambda Wi, Hi: [[(-.06, -.04), (1.06, 1.04)]]
# lowercase l: lean stem that finishes in a blade foot (differs from I and 1)
cfg.skel["l_lc"] = [[(.2, 1), (.2, .08, .9), (1, 0)]]
cfg.S0, cfg.depth_k, cfg.dcap, cfg.minsb = 74, 0.45, 120, 14
cfg.sb_adj = {}
cfg.psb = {}
cfg.space = 240
cfg.kern_t, cfg.kcap, cfg.kern_pos, cfg.kern_max, cfg.kern_min, cfg.clear = 0.5, 260, 20, 110, 10, 40
# marks
cfg.mark_h, cfg.mark_gap, cfg.mark_wmin, cfg.mark_wmax, cfg.mark_wfrac, cfg.cedilla_h = 100, 40, 130, 220, 0.5, 120
mc = copy.copy(cfg)
mc.inx, mc.iny, mc.dot_r, mc.step, mc.join_tol = 4, 3, 21, 4, 8
mc.dot = lambda cx, cy: [[(cx, cy + 30), (cx + 20, cy), (cx, cy - 30), (cx - 20, cy)]]
mc.cut = lambda k, lp, ln: 0.5 * k * min(lp, ln)
cfg.mcfg = mc

if __name__ == "__main__":
    out = os.path.join(HERE, "LyraBladeDrawn-Regular.ttf")
    data, classes, pairs = B.make_glyphs(cfg)
    # helper dotless i is exported as glyph 'dotlessi' (no cmap entry)
    fea = K.kern_fea(classes, classes, pairs)
    K.build_ttf(cfg, data, fea, out)
    print("pairs:", len(pairs))
    info = K.verify(out)
    print(info)
    K.make_specimen(out, os.path.join(HERE, "specimen.png"), "Lyra Blade Drawn")
