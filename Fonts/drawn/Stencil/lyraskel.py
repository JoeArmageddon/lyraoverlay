"""Classic (curved / diagonal) centre-line skeleton in a unit box, used by Blade and Stencil.
Points are (x, y[, k[, flag]]):  k = corner rounding 0..1, flag 'f' force free end, 'j' force joined.
A leading "C" marks a closed loop; ("dot", x, y) places a dot primitive."""


def rot(strokes):
    out = []
    for st in strokes:
        if st and st[0] == "dot":
            out.append(("dot", 1 - st[1], 1 - st[2]))
            continue
        o = []
        for it in st:
            if it == "C":
                o.append("C")
            else:
                o.append((1 - it[0], 1 - it[1]) + tuple(it[2:]))
        out.append(o)
    return out


def mirror(strokes):
    out = []
    for st in strokes:
        if st and st[0] == "dot":
            out.append(("dot", 1 - st[1], st[2]))
            continue
        o = []
        for it in st:
            o.append("C" if it == "C" else (1 - it[0], it[1]) + tuple(it[2:]))
        out.append(o)
    return out


