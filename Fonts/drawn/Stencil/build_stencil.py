#!/usr/bin/env python3
"""Lyra Stencil Drawn - heavy military stencil.  Run: /tmp/fontvenv/bin/python build_stencil.py"""
import os, sys, copy
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(1, os.path.dirname(HERE))
import lyrakit as K, lyrabuild as B, lyraskel as SK
from lyrakit import Pen


class Cfg: pass


cfg = Cfg()
cfg.name_info = dict(
    family="Lyra Stencil Drawn", ps="LyraStencilDrawn-Regular",
    copyright="Copyright (c) 2026 Lyra. Generated by build_stencil.py. Licensed under the SIL Open Font License 1.1.",
    description="Heavy military stencil display face with systematic bridges.",
    license="This Font Software is licensed under the SIL Open Font License, Version 1.1. https://openfontlicense.org")
cfg.corner = "round"
cfg.H, cfg.hsc, cfg.xheight = 700, 560, 560
cfg.W = 600
cfg.sc_w = 0.9
cfg.slant, cfg.italic_angle, cfg.weight_class = 0, 0, 800
T = 118
cfg.inx = cfg.iny = T / 2
cfg.step = 8
cfg.join_tol = 30
cfg.dot_r = 62
cfg.pen = Pen(T, miter=2.2)
cfg.mark_pen = Pen(44, miter=2.2)
cfg.clip_lo, cfg.clip_hi = 0, 0
cfg.cut = lambda k, lp, ln: min(k * 80, 0.5 * min(lp, ln))
cfg.gap, cfg.cut_len = 34, T + 70
cfg.cuts = {
    "A": [("v", .5, 1.0)], "B": [("h", .64, .77), ("h", .72, .27)], "D": [("h", 1, .5)],
    "O": [("v", .5, 0), ("v", .5, 1)], "Q": [("v", .5, 0), ("v", .5, 1)], "Oslash": [("v", .5, 0), ("v", .5, 1)],
    "P": [("h", .95, .72)], "R": [("h", .95, .75)], "0": [("v", .5, 0), ("v", .5, 1)],
    "4": [("v", .38, .65)], "6": [("h", 1, .25)], "9": [("h", 0, .75)],
    "8": [("h", .08, .76), ("h", 1, .26)],
}
def dot(cx, cy, r=62, c=18):
    return [[(cx - r + c, cy - r), (cx + r - c, cy - r), (cx + r, cy - r + c), (cx + r, cy + r - c),
             (cx + r - c, cy + r), (cx - r + c, cy + r), (cx - r, cy + r - c), (cx - r, cy - r + c)]]
cfg.dot = dot
cfg.wf = dict(A=1.12, B=.95, C=1.0, D=1.0, E=.85, F=.82, G=1.03, H=1.0, J=.86, K=1.0, L=.82, M=1.3, N=1.02,
              O=1.06, P=.94, Q=1.06, R=.97, S=.96, T=.96, U=1.02, V=1.08, W=1.6, X=1.04, Y=1.04, Z=.96, AE=1.6, sz=.96)
cfg.wf.update({"0": .9, "1": .66, "2": .9, "3": .9, "4": .96, "5": .9, "6": .92, "7": .88, "8": .92, "9": .92})
cfg.wabs = dict(I=T + 2, l_lc=210, i_lc=T + 2, j_lc=250)
cfg.pwf = {".": .2, ",": .26, "!": .24, "?": .74, "'": .2, "\"": .46, "‘": .3, "’": .3, "“": .5,
           "”": .5, "-": .56, "–": .8, "—": 1.35, ":": .2, ";": .26, "&": 1.15, "(": .5, ")": .5,
           "/": .66, "\\": .66, "#": 1.0, "@": 1.5, "%": 1.3, "+": .84, "=": .84, "$": .9, "*": .66,
           "…": 1.3, "_": .9, "~": .84, "^": .74, "<": .74, ">": .74, "[": .46, "]": .46, "{": .54, "}": .54,
           "|": .2, "`": .3, "¡": .24, "¿": .74}
cfg.pwabs = {}
cfg.skel = SK.classic()
cfg.skel["l_lc"] = [[(.2, 1), (.2, 0, .6), (1, 0)]]
cfg.skel["1"] = [[(0, .7), (.55, 1), (.55, 0)], [(0, 0), (1, 0)]]
cfg.skel["7"] = [[(0, 1), (1, 1), (.3, 0)]]
cfg.skel["="] = [[(0, .22), (1, .22)], [(0, .6), (1, .6)]]
cfg.skel["-"] = [[(0, .4), (1, .4)]]
cfg.skel["–"] = cfg.skel["—"] = cfg.skel["-"]
cfg.skel["’"] = [[(.62, 1), (.4, .62)]]
cfg.skel["‘"] = [[(.38, 1), (.6, .62)]]
cfg.skel["'"] = [[(.5, 1), (.5, .66)]]
cfg.skel["\""] = [[(.12, 1), (.12, .66)], [(.88, 1), (.88, .66)]]
cfg.skel["”"] = [[(.34, 1), (.12, .64)], [(.9, 1), (.68, .64)]]
cfg.skel["“"] = [[(.1, 1), (.32, .64)], [(.68, 1), (.9, .64)]]
cfg.skel["!"] = [[(.5, 1), (.5, .32)], ("dot", .5, 0)]
cfg.skel["¡"] = K and SK.rot(cfg.skel["!"])
cfg.oslash = lambda Wi, Hi: [[(-.08, -.06), (1.08, 1.06)]]
cfg.S0, cfg.depth_k, cfg.dcap, cfg.minsb = 60, 0.45, 120, 24
cfg.sb_adj = {}
cfg.psb = {}
cfg.space = 260
cfg.kern_t, cfg.kcap, cfg.kern_pos, cfg.kern_max, cfg.kern_min, cfg.clear = 0.5, 260, 20, 110, 10, 44
cfg.mark_h, cfg.mark_gap, cfg.mark_wmin, cfg.mark_wmax, cfg.mark_wfrac, cfg.cedilla_h = 84, 36, 150, 230, 0.45, 110
mc = copy.copy(cfg)
mc.inx = mc.iny = 22; mc.dot_r = 30; mc.step = 5; mc.join_tol = 10
mc.dot = lambda cx, cy: dot(cx, cy, 30, 8)
mc.cut = lambda k, lp, ln: min(k * 30, 0.5 * min(lp, ln))
cfg.mcfg = mc

if __name__ == "__main__":
    out = os.path.join(HERE, "LyraStencilDrawn-Regular.ttf")
    data, classes, pairs = B.make_glyphs(cfg)
    K.build_ttf(cfg, data, K.kern_fea(classes, classes, pairs), out)
    print("pairs:", len(pairs)); print(K.verify(out))
    K.make_specimen(out, os.path.join(HERE, "specimen.png"), "Lyra Stencil Drawn")
