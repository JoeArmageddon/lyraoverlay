/// 5x7 bitmap glyphs for the Pixel font. `rows` run top to bottom; the last `below` rows hang
/// under the baseline (commas, underscores, the tail of a semicolon).
struct Bitmap {
    var rows: [String]
    var below = 0
    var width: Int { rows.map(\.count).max() ?? 0 }

    func rotated180() -> Bitmap {
        Bitmap(rows: rows.reversed().map { String($0.reversed()) }, below: 0)
    }
}

